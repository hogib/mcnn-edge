"""Generate runtime/weights.h from an int_model.json (M2 export) and golden
test vectors (runtime/tests/golden.h) from golden.npz.

  uv run python -m sonar_edge.export_c runs/<name>

Layout conventions for the C runtime (HWC):
  weights  [cout][ky][kx][cin]  int8   (cin innermost: contiguous dot products)
  head     [cout][cin]          int8
"""

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]


def c_array(name, ctype, values, per_line=24):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    vals = [str(int(v)) for v in values]
    for i in range(0, len(vals), per_line):
        lines.append("  " + ", ".join(vals[i : i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def write_weights(model, in_h, in_w, out: Path):
    L = model["layers"]
    parts = ["/* Generated by sonar_edge.export_c. Do not edit. */", "#pragma once", "#include <stdint.h>", ""]
    parts.append(f"#define SE_IN_H {in_h}")
    parts.append(f"#define SE_IN_W {in_w}")
    parts.append(f"#define SE_N_CLASSES {model['n_classes']}")
    parts.append(f"#define SE_STRIDE {model['stride']}")
    parts.append(f"#define SE_N_LAYERS {len(L)}")
    parts.append(f"#define SE_HEAD_COUT {model['head']['cout']}")
    parts.append(f"#define SE_HEAD_CIN {model['head']['cin']}")
    # per-layer geometry and the largest activation buffer (padded, HWC)
    h, w, max_elems, max_pad = in_h, in_w, 0, 0
    geom = []
    for layer in L:
        d, s = layer["dilation"], layer["stride"]
        max_pad = max(max_pad, d)
        in_elems = (h + 2 * d) * (w + 2 * d) * layer["cin"]
        h = (h + 2 * d - 2 * d - 1) // s + 1
        w = (w + 2 * d - 2 * d - 1) // s + 1
        max_elems = max(max_elems, in_elems)
        geom.append((layer["cin"], layer["cout"], s, d))
    # the output of the last layer feeds the head (no padding needed) but may be
    # stored padded for uniformity; include its padded size too
    max_elems = max(max_elems, (h + 2 * max_pad) * (w + 2 * max_pad) * L[-1]["cout"])
    parts.append(f"#define SE_OUT_H {h}")
    parts.append(f"#define SE_OUT_W {w}")
    parts.append(f"#define SE_MAX_PAD {max_pad}")
    parts.append(f"#define SE_ACT_ELEMS {max_elems}")
    parts.append("")
    parts.append("typedef struct { int cin, cout, stride, dilation; const int8_t *w; const int32_t *bias; "
                 "const int32_t *mult; const int8_t *shift; } se_layer_t;")
    parts.append("")
    for i, layer in enumerate(L):
        w = np.array(layer["w"], np.int8).reshape(layer["cout"], layer["cin"], 3, 3)
        w = w.transpose(0, 2, 3, 1)  # cout, ky, kx, cin
        parts.append(c_array(f"se_w{i}", "int8_t", w.flatten()))
        parts.append(c_array(f"se_b{i}", "int32_t", layer["bias"]))
        parts.append(c_array(f"se_m{i}", "int32_t", layer["M"]))
        parts.append(c_array(f"se_s{i}", "int8_t", layer["shift"]))
        parts.append("")
    parts.append("static const se_layer_t se_layers[SE_N_LAYERS] = {")
    for i, (cin, cout, s, d) in enumerate(geom):
        parts.append(f"  {{ {cin}, {cout}, {s}, {d}, se_w{i}, se_b{i}, se_m{i}, se_s{i} }},")
    parts.append("};")
    parts.append("")
    head = model["head"]
    parts.append(c_array("se_head_w", "int8_t", head["w"]))
    parts.append(c_array("se_head_b", "int32_t", head["bias"]))
    # head scales as float for the decoder's final box arithmetic; also as Q16 integers
    sc = np.array(head["scale"])
    parts.append("static const float se_head_scale[SE_HEAD_COUT] = {" + ", ".join(f"{v:.9e}f" for v in sc) + "};")
    parts.append("")
    out.write_text("\n".join(parts) + "\n")
    return max_elems


def write_golden(npz, out: Path):
    g = np.load(npz)
    imgs, head = g["images"], g["head"]
    n, h, w = imgs.shape
    parts = ["/* Generated by sonar_edge.export_c. Do not edit. */", "#pragma once", "#include <stdint.h>", ""]
    parts.append(f"#define GOLD_N {n}")
    parts.append(f"#define GOLD_HEAD_C {head.shape[1]}")
    parts.append(f"#define GOLD_HEAD_H {head.shape[2]}")
    parts.append(f"#define GOLD_HEAD_W {head.shape[3]}")
    parts.append(c_array("gold_images", "uint8_t", imgs.flatten(), 32))
    # head stored HWC to match the runtime's output layout
    parts.append(c_array("gold_head", "int32_t", head.transpose(0, 2, 3, 1).flatten(), 16))
    parts.append(c_array("gold_frame_index", "int32_t", g["frame_index"]))
    out.write_text("\n".join(parts) + "\n")


def main():
    run = ROOT / sys.argv[1]
    model = json.loads((run / "int_model.json").read_text())
    g = np.load(run / "golden.npz")
    _, in_h, in_w = g["images"].shape
    (ROOT / "runtime").mkdir(exist_ok=True)
    (ROOT / "runtime/tests").mkdir(exist_ok=True)
    elems = write_weights(model, in_h, in_w, ROOT / "runtime/weights.h")
    write_golden(run / "golden.npz", ROOT / "runtime/tests/golden.h")
    n_w = sum(len(l["w"]) for l in model["layers"]) + len(model["head"]["w"])
    print(f"wrote runtime/weights.h ({n_w:,} int8 weights, input {in_h}x{in_w}, activation buffer {elems:,} B) "
          f"and runtime/tests/golden.h ({len(g['images'])} frames)")


if __name__ == "__main__":
    main()
